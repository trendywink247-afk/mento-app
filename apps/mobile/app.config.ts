/**
 * Dynamic layer over app.json: explicit profile channels and production cleartext
 * policy. Default preview preserves local/CI builds without an explicit variant.
 *
 * Development talks to a LAN API over http:// (CLAUDE.md "Phone testing"), so every
 * non-production build keeps cleartext on. A production build (`ops/build-android.sh prod`,
 * or `scripts/build-android-release.ps1`) sets APP_VARIANT=production and
 * gets Android's default block-all-cleartext policy: prod is https-only.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import type { ConfigContext, ExpoConfig } from 'expo/config';

/** True when the Firebase client config lists this Android package, so a QA package is only
 * given push once someone has registered it in Firebase and refreshed google-services.json. */
function firebaseKnows(file: string, androidPackage: string): boolean {
  try {
    const parsed = JSON.parse(readFileSync(resolve(__dirname, file), 'utf8')) as {
      client?: { client_info?: { android_client_info?: { package_name?: string } } }[];
    };
    return (parsed.client ?? []).some(
      (c) => c.client_info?.android_client_info?.package_name === androidPackage,
    );
  } catch {
    return false;
  }
}

/** Update server per variant. Prod's certificate is generated by the founder (docs/OTA.md);
 * only the public certificate is in the repo, the signing keys never are. */
const OTA = {
  preview: { url: 'https://qa-api.mento.chat/ota/api/manifest', cert: './certs/ota-qa.pem' },
  production: { url: 'https://api.mento.chat/ota/api/manifest', cert: './certs/ota-prod.pem' },
} as const;

export default ({ config }: ConfigContext): ExpoConfig => {
  const variant = process.env.APP_VARIANT ?? 'preview';
  if (!['development', 'preview', 'production'].includes(variant)) {
    throw new Error('APP_VARIANT must be development, preview or production');
  }
  const isProduction = variant === 'production';
  const plugins = (config.plugins ?? []).map((plugin) => {
    if (!Array.isArray(plugin) || plugin[0] !== 'expo-build-properties') return plugin;
    const [name, props = {}] = plugin;
    return [name, { ...props, android: { ...props.android, usesCleartextTraffic: !isProduction } }];
  });
  // reason: `config` is app.json, which always carries name + slug; ConfigContext types
  // it as Partial<ExpoConfig> only because a bare app.config.ts may have no app.json.
  // Self-hosted OTA (services/ota, docs/OTA.md). Each variant has its own server, channel and
  // signing certificate; development never loads an update. No Expo cloud service is involved.
  const ota = variant === 'production' ? OTA.production : OTA.preview;
  const updates = variant === 'development'
    ? { enabled: false, checkAutomatically: 'NEVER' as const }
    : {
      ...config.updates,
      url: ota.url,
      codeSigningCertificate: ota.cert,
      codeSigningMetadata: { keyid: 'main', alg: 'rsa-v1_5-sha256' as const },
      requestHeaders: { ...config.updates?.requestHeaders, 'expo-channel-name': variant },
    };
  const localAcceptance = process.env.MENTO_LOCAL_ACCEPTANCE;
  if (localAcceptance !== undefined && localAcceptance !== '0' && localAcceptance !== '1') {
    throw new Error('MENTO_LOCAL_ACCEPTANCE must be 0 or 1');
  }
  if (localAcceptance === '1') {
    // Separate synthetic install: never replace a member's app or load an OTA.
    // This is intentionally not a store build or a provider-push build.
    if (variant !== 'development'
        || process.env.EXPO_NO_DOTENV !== '1'
        || process.env.EXPO_PUBLIC_API_URL !== 'http://localhost:18000/api/v1'
        || process.env.EXPO_PUBLIC_OWN_CHAT_ACCEPTED !== '1'
        || process.env.EXPO_PUBLIC_OWN_CHAT_NATIVE_ACCEPTED !== '1'
        || ['EXPO_PUBLIC_STREAM_API_KEY', 'EXPO_PUBLIC_POSTHOG_KEY', 'EXPO_PUBLIC_SENTRY_DSN']
          .some(key => Boolean(process.env[key]))) {
      throw new Error('Local acceptance requires isolated own-chat settings and no provider keys');
    }
    const { googleServicesFile: _androidServices, ...android } = config.android ?? {};
    const { googleServicesFile: _iosServices, ...ios } = config.ios ?? {};
    const extra = config.extra ?? {};
    // eslint-disable-next-line @typescript-eslint/no-var-requires -- plugin module, not a type import
    const withLocalAcceptanceCmakeVersion = require('./plugins/withLocalAcceptanceCmakeVersion');
    return {
      ...config, plugins: [...plugins, withLocalAcceptanceCmakeVersion],
      name: 'Mento Acceptance', scheme: 'mento-acceptance',
      android: { ...android, package: 'com.mento.acceptance' },
      ios: { ...ios, bundleIdentifier: 'com.mento.acceptance' },
      extra: { ...extra, localAcceptance: true },
      updates: { enabled: false, checkAutomatically: 'NEVER' },
    } as ExpoConfig;
  }
  // Production only: unsigned release bundle (or upload-key signing from env), never the debug key.
  const releasePlugins = isProduction ? [...plugins, './plugins/withReleaseSigning'] : plugins;
  if (isProduction) return { ...config, plugins: releasePlugins, updates } as ExpoConfig;
  // Development and preview builds install BESIDE the store build instead of replacing it: a
  // separate package ("Mento QA") means the Play build and the QA build coexist on one phone,
  // each keeping its own member and its own update channel. Push needs the package registered
  // in Firebase, so the Firebase file is only attached once it lists the QA package.
  const storePackage = config.android?.package ?? 'chat.mento.app';
  const qaPackage = `${storePackage}.qa`;
  const { googleServicesFile, ...android } = config.android ?? {};
  return {
    ...config,
    name: `${config.name ?? 'Mento'} QA`,
    plugins: releasePlugins,
    updates,
    ios: { ...config.ios, bundleIdentifier: `${config.ios?.bundleIdentifier ?? storePackage}.qa` },
    android: {
      ...android,
      package: qaPackage,
      ...(googleServicesFile && firebaseKnows(googleServicesFile, qaPackage) ? { googleServicesFile } : {}),
    },
  } as ExpoConfig;
};
